#!/usr/bin/env node
// Converts public/career-cast-jingle.mp3 to 24 kHz mono 16-bit PCM, base64
// encodes it, and emits lib/podcast/jingle-pcm.ts. Re-run whenever the jingle
// source changes. Requires ffmpeg on PATH.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const src = join(root, "public", "career-cast-jingle.mp3");
const out = join(root, "lib", "podcast", "jingle-pcm.ts");

const SAMPLE_RATE = 24000;
const CHANNELS = 1;
const BITS_PER_SAMPLE = 16;

const tmp = mkdtempSync(join(tmpdir(), "jingle-"));
const pcmPath = join(tmp, "jingle.pcm");
try {
  execFileSync(
    "ffmpeg",
    [
      "-y",
      "-i", src,
      "-ar", String(SAMPLE_RATE),
      "-ac", String(CHANNELS),
      "-f", "s16le",
      "-acodec", "pcm_s16le",
      pcmPath,
    ],
    { stdio: ["ignore", "ignore", "inherit"] },
  );
  const pcm = readFileSync(pcmPath);
  const base64 = pcm.toString("base64");
  const bytesPerSecond = (SAMPLE_RATE * CHANNELS * BITS_PER_SAMPLE) / 8;
  const seconds = pcm.length / bytesPerSecond;

  const body = `// AUTO-GENERATED by scripts/build-jingle-pcm.mjs — do not edit by hand.
// Source: public/career-cast-jingle.mp3
// Format: ${SAMPLE_RATE} Hz, ${CHANNELS}ch, ${BITS_PER_SAMPLE}-bit signed little-endian PCM.
// Duration: ${seconds.toFixed(3)}s (${pcm.length} bytes raw, ${base64.length} bytes base64).

export const JINGLE_SAMPLE_RATE = ${SAMPLE_RATE};
export const JINGLE_CHANNELS = ${CHANNELS};
export const JINGLE_BITS_PER_SAMPLE = ${BITS_PER_SAMPLE};
export const JINGLE_DURATION_SECONDS = ${seconds};
export const JINGLE_PCM_BASE64 = ${JSON.stringify(base64)};
`;
  writeFileSync(out, body);
  console.log(`Wrote ${out} (${seconds.toFixed(2)}s, ${(pcm.length / 1024).toFixed(0)} KiB raw)`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
